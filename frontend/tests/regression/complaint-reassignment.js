const fixture = reloaded.A.db.incidents.find(x => x.id === fixtureIds[0]);
fixture.assignmentNote = 'Keep existing user edits';
reloaded.A.save();
const cached = createApp(root, { localStorage: reloaded.localStorage });
fixtureIds.forEach(id => assert.strictEqual(cached.A.db.incidents.filter(x => x.id === id).length, 1));
assert.strictEqual(cached.A.db.incidents.find(x => x.id === fixture.id).assignmentNote, 'Keep existing user edits');
cached.A.db.incidents = cached.A.db.incidents.filter(x => !fixtureIds.includes(x.id));
cached.A.save();
const migrated = createApp(root, { localStorage: cached.localStorage });
fixtureIds.forEach(id => assert.strictEqual(migrated.A.db.incidents.filter(x => x.id === id).length, 1));
